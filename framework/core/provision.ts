// Provisioning: a project's roles are code in its .baba/ directory, and what the harnesses beside it are given is one
// thing, the content that makes an agent aware of them. Where a harness has hooks, the framework's hook delivers it: the
// skill baba's words and the root's present at a session's start, the present's changes after. The skill baba itself is
// written too, for harnesses without hooks and as the way back in. Roles get no skills of their own: a role teaches
// the agent by its tab on the root's surface, where its own know-how, from its ROLE.md, stands among its facts.
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { basename, dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

/** Where the harnesses read skills, relative to a project or to the person's home: Claude Code, and Codex with the rest. */
export const SKILL_FOLDERS = [".claude/skills", ".agents/skills"]
export const ROLES_DIR = "roles"
/** The harness events the framework's hook is provisioned for: it adds context there and blocks nothing. */
export const HOOK_EVENTS = ["SessionStart", "UserPromptSubmit", "PostToolUse"]
/** Claude Code's settings beside .baba/: the person's too, so only the framework's own hooks in it are written. */
const SETTINGS = ".claude/settings.json"
/** How the framework's hooks are told from the person's: by the command they run. */
const HOOK = '/.baba/node_modules/babavoss/bin/baba.ts" hook'
const NAME = /^[a-z][a-z0-9-]*$/
/** Names a role cannot take: the root's and its own util's. */
export const RESERVED = ["baba", "roles"]
const BABA = fileURLToPath(new URL("../../skill/SKILL.md", import.meta.url))

/** A role's ROLE.md: its description, and under the frontmatter its own know-how. */
function readRole(file: string): { description: string; body: string } {
  const text = readFileSync(file, "utf8")
  const front = /^---\n([\s\S]*?)\n---\n?/.exec(text)
  const description = /^description:\s*(.+)$/m.exec(front?.[1] ?? "")?.[1]?.trim()

  if (!description) throw new Error(`${file} has no description: start it with\n---\ndescription: what the role does. Use when ...\n---`)

  return { description, body: text.slice(front![0].length).trim() }
}

/** The roles in a .baba/ directory, by name: each directory under roles/ with a ROLE.md and a surface, src/role.ts. */
export function roles(baba: string): string[] {
  const dir = join(baba, ROLES_DIR)

  return (existsSync(dir) ? readdirSync(dir).sort() : []).filter((name) => existsSync(join(dir, name, "ROLE.md")) && existsSync(join(dir, name, "src/role.ts")))
}

/** Where the root of a .baba/ is generated: the roles' surfaces as one module, and the page that holds each in its tab. */
export const ROOT_DIR = ".root"

const written = (file: string, text: string) => {
  // Only what differs is written: the running root loads a changed file again.
  if (existsSync(file) && readFileSync(file, "utf8") === text) return
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
}

/**
 * Generates the root of `baba` from its roles, and answers with its directory: roles.ts, the surfaces by name and what
 * each role's ROLE.md tells, which the root's runtime imports; and the page, index.html, main.tsx and styles.css, the shell with each role's component.
 */
export function generateRoot(baba: string): string {
  const dir = join(baba, ROOT_DIR)
  const names = roles(baba)
  const paged = names.filter((name) => existsSync(join(baba, ROLES_DIR, name, "ui/index.tsx")))
  const head = "// Generated by baba from the roles in this .baba/: change a role, not this.\n"

  written(
    join(dir, "roles.ts"),
    `${head}${names.map((name, i) => `import r${i} from "../${ROLES_DIR}/${name}/src/role.ts"\n`).join("")}\nexport default { ${names.map((name, i) => `${JSON.stringify(name)}: r${i}`).join(", ")} }\nexport const described = ${JSON.stringify(describedRoles(baba), null, 2)}\n`
  )
  written(
    join(dir, "main.tsx"),
    `${head}import { createRoot } from "react-dom/client"\nimport { UsersIcon } from "lucide-react"\nimport { Shell, type Registry } from "babavoss/shell/ui/index.ts"\nimport { Roles } from "babavoss/root/ui/roles.tsx"\n` +
      paged.map((name, i) => `import * as p${i} from "../${ROLES_DIR}/${name}/ui/index.tsx"\n`).join("") +
      `import "./styles.css"\n\nconst pages: Record<string, { default: Registry[string]["component"]; icon?: Registry[string]["icon"] }> = { ${paged.map((name, i) => `${JSON.stringify(name)}: p${i}`).join(", ")} }\n` +
      `const utils: Registry = { roles: { component: Roles, icon: <UsersIcon aria-hidden /> } }\n\n` +
      `for (const [name, page] of Object.entries(pages)) utils[name] = { component: page.default, icon: page.icon }\ncreateRoot(document.getElementById("root")!).render(<Shell utils={utils} />)\n`
  )
  written(join(dir, "styles.css"), `/* Generated by baba. The page uses the shell's design language. */\n@import "babavoss/shell/ui/styles.css";\n\n@source "../${ROLES_DIR}";\n`)
  written(join(dir, "index.html"), readFileSync(new URL("../root/ui/index.html", import.meta.url), "utf8"))

  return dir
}

/** A role as its ROLE.md tells it: what it does and when to use it, and its own know-how, empty where it has none. */
export type Described = { name: string; description: string; knowhow: string }

/** The roles in a .baba/ directory as their ROLE.md tells them; one whose ROLE.md has no description says so in its place. */
export const describedRoles = (baba: string): Described[] =>
  roles(baba).map((name) => {
    try {
      const { description, body } = readRole(join(baba, ROLES_DIR, name, "ROLE.md"))

      return { name, description, knowhow: body }
    } catch {
      return { name, description: "ROLE.md has no description yet", knowhow: "" }
    }
  })

/** The .baba/ directory of a directory: the one it is, or the nearest in it or above; undefined where there is none. */
export function findBaba(from: string): string | undefined {
  for (let dir = resolve(from); ; dir = dirname(dir)) {
    const baba = basename(dir) === ".baba" ? dir : join(dir, ".baba")

    if (existsSync(join(baba, "package.json"))) return baba
    if (dir === dirname(dir)) return undefined
  }
}

type Handler = { type?: string; command?: string }
type Group = { matcher?: string; hooks?: Handler[] }
type Settings = { hooks?: Record<string, Group[]> } & Record<string, unknown>

/**
 * Writes the framework's hook into Claude Code's settings beside `baba`, for each of its events, and leaves everything
 * else in the file as it is: the person's settings and their own hooks.
 */
export function provisionHooks(baba: string) {
  const root = dirname(baba)
  const file = join(root, SETTINGS)
  let settings: Settings

  try {
    settings = existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as Settings) : {}
  } catch {
    throw new Error(`${file} is not JSON: correct it, and provision again`)
  }

  // Under a project the harness names its root; under the person's home, the home is it. Silent where bun or the package is missing.
  const dir = root === realpathSync(homedir()) ? "$HOME" : "${CLAUDE_PROJECT_DIR}"
  const ours: Group = { hooks: [{ type: "command", command: `bun "${dir}${HOOK} 2>/dev/null || true` }] }
  const hooks: Record<string, Group[]> = {}

  for (const [event, groups] of Object.entries(settings.hooks ?? {})) {
    const kept = groups
      .map((group) => ({ ...group, hooks: (group.hooks ?? []).filter((handler) => !handler.command?.includes(HOOK)) }))
      .filter((group) => group.hooks.length)

    if (kept.length) hooks[event] = kept
  }
  for (const event of HOOK_EVENTS) hooks[event] = [...(hooks[event] ?? []), ours]
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, `${JSON.stringify({ ...settings, hooks }, null, 2)}\n`)
}

/**
 * Provisions `baba`, a .baba/ directory: the skill baba in the harnesses' skill folders beside it, the framework's hook
 * in Claude Code's settings there, and the root generated from the roles. Answers with what it wrote, relative to the
 * directory .baba/ is in.
 */
export function provision(baba: string): string[] {
  const root = dirname(baba)
  const skill = readFileSync(BABA, "utf8")

  for (const name of roles(baba))
    if (!NAME.test(name) || RESERVED.includes(name)) throw new Error(`${join(baba, ROLES_DIR, name)}: a role's name is lowercase kebab-case, and not ${RESERVED.join(" or ")}`)
  for (const folder of SKILL_FOLDERS) written(join(root, folder, "baba", "SKILL.md"), skill)
  provisionHooks(baba)
  generateRoot(baba)

  return [...SKILL_FOLDERS.map((folder) => join(folder, "baba")), SETTINGS, relative(root, join(baba, ROOT_DIR))]
}
